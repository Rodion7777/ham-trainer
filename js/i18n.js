window.t = function (key) {
  var lang = (window.Store && Store.settings && Store.settings()) ? Store.settings().lang : 'pl';
  var dict = window.I18N[lang] || window.I18N.pl;
  var s = dict[key];
  if (s == null) s = (window.I18N.en[key] != null ? window.I18N.en[key] : key);
  if (arguments.length > 1) {
    for (var i = 1; i < arguments.length; i++) {
      s = s.replace('{' + (i - 1) + '}', arguments[i]);
    }
  }
  return s;
};

// inline bilingual string: tt({pl:'...', en:'...'})
window.tt = function (obj) {
  if (!obj) return '';
  if (typeof obj === 'string') return obj;
  var lang = (window.Store && Store.settings && Store.settings()) ? Store.settings().lang : 'pl';
  return obj[lang] != null ? obj[lang] : (obj.en != null ? obj.en : obj.pl);
};
